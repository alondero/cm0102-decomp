"""Compiler-generated entries proven from metadata in the pinned image, bound to their parents.

The image itself proves each kind; instruction shape alone does not:

- `unwind-funclet`: an action in the unwind map of a C++ EH FuncInfo (magic
  0x1993052x). FuncInfo is named by one handler stub (`mov eax, FuncInfo; jmp
  frame-handler`), and one `push stub` registers that stub in the parent's prologue.
- `seh-finally`: a termination handler (null filter) in a scope table registered
  by `push -1; push table; push handler; mov eax, fs:[0]`.
- `import-thunk`: a single `jmp [slot]` through a named import address table slot.

Funclets are regenerated by compiling the parent's C++/SEH; thunks by linking the
import library. `parents()` names the inventory entry whose decoded instructions
contain each registration site; a site outside every entry is an open exception.
"""
from __future__ import annotations

import functools
import re
import struct
from dataclasses import dataclass

from . import image, inventory

FUNCINFO_MAGIC = (0x19930520, 0x19930521, 0x19930522)
REGENERATION = {
    "unwind-funclet": "compiler: C++ EH unwind action of the parent's FuncInfo",
    "seh-finally": "compiler: SEH termination handler of the parent's scope table",
    "import-thunk": "linker: import library thunk",
}


@dataclass(frozen=True)
class Proof:
    va: int
    kind: str
    metadata: int | None  # FuncInfo or scope table VA
    site: int | None  # instruction VA that registers the metadata in the parent
    import_name: str | None = None


def _rdata():
    return next(s for s in image.primary().sections if s.name == ".rdata")


@functools.cache
def _cxx() -> dict:
    """FuncInfo VA -> (handler stub VA, registration site VA), for stubs registered exactly once."""
    img = image.primary()
    text, rdata = img.text, _rdata()
    raw = rdata.raw
    infos = {rdata.va + o for o in range(0, len(raw) - 3, 4)
             if struct.unpack_from("<I", raw, o)[0] in FUNCINFO_MAGIC}
    stubs: dict[int, list[int]] = {}
    for m in re.finditer(rb"(?=\xb8(....)\xe9)", text.raw, re.S):
        info = struct.unpack("<I", m.group(1))[0]
        if info in infos:
            stubs.setdefault(info, []).append(text.va + m.start())
    by_stub = {s[0]: info for info, s in stubs.items() if len(s) == 1}
    sites: dict[int, list[int]] = {}
    for m in re.finditer(rb"(?=\x68(....))", text.raw, re.S):
        stub = struct.unpack("<I", m.group(1))[0]
        if stub in by_stub:
            sites.setdefault(stub, []).append(text.va + m.start())
    return {info: (stub, s[0]) for stub, info in by_stub.items() if len(s := sites.get(stub, [])) == 1}


@functools.cache
def _seh() -> dict:
    """Scope table VA -> registration site VA."""
    text, rdata = image.primary().text, _rdata()
    out: dict[int, list[int]] = {}
    for m in re.finditer(rb"(?=\x6a\xff\x68(....)\x68....\x64\xa1\x00\x00\x00\x00)", text.raw, re.S):
        table = struct.unpack("<I", m.group(1))[0]
        if rdata.va <= table < rdata.end:
            out.setdefault(table, []).append(text.va + m.start())
    return {t: s[0] for t, s in out.items() if len(s) == 1}


@functools.cache
def proofs() -> dict[int, Proof]:
    """Inventory entry VA -> proof. Only metadata-backed entries appear."""
    from . import lift

    img = image.primary()
    text = img.text
    entries = inventory.load().functions
    out: dict[int, Proof] = {}

    def add(proof: Proof) -> None:
        if proof.va in entries and proof.va not in out:
            out[proof.va] = proof

    for info, (_, site) in sorted(_cxx().items()):
        states, unwind = struct.unpack("<iI", img.read(info + 4, 8))
        if not 0 < states <= 0x10000 or img.section_at(unwind) is None:
            continue
        for state in range(states):
            to_state, action = struct.unpack("<iI", img.read(unwind + 8 * state, 8))
            if action and -1 <= to_state < state and text.va <= action < text.end:
                add(Proof(action, "unwind-funclet", info, site))
    tables = _seh()
    for table, site in sorted(tables.items()):
        level = 0
        while level == 0 or table + 12 * level not in tables:
            previous, filter_, handler = struct.unpack("<iII", img.read(table + 12 * level, 12))
            if not (previous == -1 or 0 <= previous < level) or not text.va <= handler < text.end:
                break
            if filter_ == 0:
                add(Proof(handler, "seh-finally", table, site))
            level += 1
    for va, f in entries.items():
        if f.body_bytes <= 6 and va not in out:
            try:
                insns = list(lift.discover(va).insns.values())
            except Exception:  # noqa: BLE001 - undiscoverable entries are not thunks
                continue
            if len(insns) == 1 and insns[0].kind == "import_jmp":
                slot = struct.unpack("<I", insns[0].raw[2:6])[0]
                if slot in img.imports:
                    add(Proof(va, "import-thunk", slot, None, img.imports[slot]))
    return dict(sorted(out.items()))


def kind(va: int) -> str | None:
    proof = proofs().get(va)
    return proof.kind if proof else None


def owner(site: int) -> int | None:
    """The inventory entry whose decoded instructions include `site`, else None."""
    import bisect

    from . import lift

    inv = inventory.load()
    i = bisect.bisect_right(inv.entries_sorted, site) - 1
    if i < 0:
        return None
    va = inv.entries_sorted[i]
    try:
        return va if site in lift.discover(va).insns else None
    except BaseException:  # noqa: BLE001 - discover exits on unrecoverable regions
        return None


@functools.cache
def parents() -> dict[int, int | None]:
    """Registration site -> owning inventory entry (None: no entry owns it)."""
    return {site: owner(site) for site in sorted({p.site for p in proofs().values() if p.site is not None})}
