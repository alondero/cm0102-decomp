def _va(text: str) -> int:
    text = text.lower().removeprefix("fn_")
    return int(text, 16)


def _shard(text: str) -> tuple[int, int]:
    try:
        k, n = (int(part) for part in text.split("/"))
    except ValueError:
        raise argparse.ArgumentTypeError("expected K/N, for example 2/4") from None
    if not 1 <= k <= n:
        raise argparse.ArgumentTypeError("expected 1 <= K <= N")
    return k, n


def cmd_doctor(a) -> int:
    from . import image, inventory, ledger

    ok = True

    def line(good: bool, what: str, detail: str = "") -> None:
        nonlocal ok
        ok &= good
        print(f"{'ok ' if good else 'BAD'} {what}{': ' + detail if detail else ''}")

    line(sys.version_info[:2] == env.PYTHON_REQUIRED, "python", sys.version.split()[0] + " (use `py -3.13`)")
    try:
        import capstone, unicorn, pefile  # noqa: F401

        line(True, "packages", f"unicorn {unicorn.__version__}, capstone {capstone.__version__}")
    except ImportError as exc:
        line(False, "packages", str(exc))
    try:
        tc = env.toolchain_identity()
        line(True, "toolchain", tc["gcc"]["version"])
    except Exception as exc:  # noqa: BLE001
        line(False, "toolchain", f"{env.TOOLCHAIN}: {exc}")
    line(env.TARGET.exists() and env.digest(env.TARGET) == env.TARGET_SHA256, "target", env.rel(env.TARGET))
    for path, want in env.INVENTORY_SHA256.items():
        line(path.exists() and env.digest(path) == want, "inventory", env.rel(path))
    if ok:
        image.primary()
        inventory.load()
        problems = ledger.verify()
        line(not problems, "ledgers", f"{len(problems)} problem(s)" if problems else "verified")
    return 0 if ok else 1


def cmd_status(a) -> int:
    from . import queue

    s = queue.coverage_summary()
    if a.json:
        print(json.dumps(s, indent=2))
    else:
        print(f"accepted C/legacy {s['source_functions']} functions, "
              f"{s['source_body_bytes']}/{s['inventory_body_bytes']} inventory body bytes ({s['source_percent']}%)")
        print(f"recovered {s['recovered_functions']}/{s['inventory_functions']} functions, "
              f"{s['recovered_body_bytes']}/{s['inventory_body_bytes']} body bytes ({s['recovered_percent']}%)")
        print(f"  legacy {s['legacy_functions']}  lifted {s['lifted_functions']}  c-tier {s['c_tier_functions']}  "
              f"blocked {s['blocked_functions']}  integrated {s['integrated_functions']}")
        print(f"  compiler-generated (metadata-proven funclets and import thunks; outside the C queue) "
              f"{s['compiler_generated_functions']} functions, {s['compiler_generated_body_bytes']} bytes")
        if s['source_unmapped_functions']:
            print(f"  {s['source_unmapped_functions']} accepted C/legacy functions absent from inventory; "
                  "excluded from byte coverage")
    if a.write:
        _write_status(s)
    return 0


def _write_status(s: dict) -> None:
    from . import ledger

    blocked = ledger.blocked()
    reasons: dict[str, int] = {}
    for r in blocked.values():
        key = r["reason"].split(":")[0]
        reasons[key] = reasons.get(key, 0) + 1
    lines = [
        "# Recovery status",
        "",
        "Generated by `py -3.13 -m cmre status --write`; do not edit by hand.",
        "",
        "| Measure | Value |",
        "| --- | --- |",
    ]
    lines += [f"| {k.replace('_', ' ')} | {v} |" for k, v in s.items()]
    lines += ["", "Recovered coverage includes lifted assembly; C-tier is a subset of lifted records.",
              "Source coverage counts accepted C/legacy inventory body bytes, excluding unmapped entries.",
              "C-tier can retain assembly and compiler-specific adapters; these counters do not certify",
              "portable source, subsystem parity, or a standalone game."]
    lines += ["", "## Blocked by reason", "", "| Reason | Functions |", "| --- | --- |"]
    lines += [f"| {k} | {v} |" for k, v in sorted(reasons.items())] or ["| none | 0 |"]
    (env.ROOT / "docs/STATUS.md").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print("wrote docs/STATUS.md")


def cmd_next(a) -> int:
    from . import ledger, queue

    if a.blocked:
        items = sorted(ledger.blocked().items(), key=lambda kv: (kv[1].get("by") != "batch", kv[0]))
        for va, r in items[: a.n]:
            print(f"fn_{va:08x}  {r['reason'][:110]}")
        return 0
    claim, shard = getattr(a, "claim", None), getattr(a, "shard", None)
    if (claim or shard) and not a.c:
        print("--claim and --shard apply to the C queue (--c)", file=sys.stderr)
        return 2
    filters = dict(max_bytes=a.max_bytes, include_generated=a.include_generated, min_bytes=a.min_bytes,
                   module=a.module, shard=shard)
    if claim:
        items = queue.claim_next(a.n, claim, a.claim_hours, **filters)
    elif a.c:
        items = queue.c_frontier(a.n, include_held=getattr(a, "include_held", False), **filters)
    else:
        items = queue.frontier(a.n, a.max_bytes, a.min_bytes, a.module)
    for i in items:
        print(f"fn_{i.va:08x} {i.body_bytes:6d}B {'ready' if i.ready else f'waits:{i.pending_callees}':8s} {i.module}")
    return 0


def cmd_show(a) -> int:
    from . import inventory, ledger, lift

    va = _va(a.va)
    inv = inventory.load()
    f = inv.functions[va]
    rec = ledger.recovered()
    lifted = lift.discover(va)
    print(f"fn_{va:08x} {f.name} body={f.body_bytes}B region_end={lifted.region_end:#010x} sig={f.signature}")
    print(f"module: {', '.join(inv.modules.get(va, [])) or 'unknown'}")
    print("callees: " + (" ".join(f"{c:#010x}{'*' if c in rec else ''}" for c in lifted.callees) or "none")
          + "   (* = recovered)")
    print("imports: " + (", ".join(lifted.imports) or "none"))
    for p in lifted.problems:
        print(f"PROBLEM {p}")
    bp = ledger.blocked_path(va)
    if bp.exists():
        print("blocked: " + json.loads(bp.read_text(encoding="utf-8"))["reason"])
    if a.asm:
        sys.stdout.write(lift.render(lifted))
    return 0


def cmd_brief(a) -> int:
    from . import drafts

    if a.packet:
        from . import evidence

        if a.no_asm:
            raise ValueError("--packet retains the original listing; use --no-asm with a plain brief")
        path, reused = evidence.packet(_va(a.va), _va(a.peer) if a.peer else None)
        print(f"packet {'reused' if reused else 'prepared'}: {env.rel(path)}")
        print(f"manifest: {env.rel(path.with_suffix('.json'))}")
        print("Read needed sections from the packet; all indexed direct callers are included. Acceptance is unchanged.")
        return 0
    if a.peer:
        raise ValueError("--peer requires --packet")
    sys.stdout.write(drafts.brief(_va(a.va), asm=not a.no_asm))
    return 0


def cmd_disasm(a) -> int:
    """Decode a bounded window of pinned file bytes, independent of function ownership."""
    import capstone
    from . import image

    if not 1 <= a.count <= 256:
        print("instruction count must be in 1..256", file=sys.stderr)
        return 2
    img = image.primary()
    va = a.va
    pointer_line = None
    if a.indirect:
        pointer_section = img.section_at(va)
        if (pointer_section is None or va + 4 > pointer_section.end
                or va + 4 > pointer_section.va + len(pointer_section.raw)):
            print(f"no file-backed DWORD at preferred-image VA {va:#010x}", file=sys.stderr)
            return 2
        target = img.dword(va)
        pointer_line = f"pointer {va:#010x} -> {target:#010x}"
        va = target
    section = img.section_at(va)
    if section is None or not section.executable:
        print(f"preferred-image VA {va:#010x} is not in an executable section", file=sys.stderr)
        return 2
    start = va - section.va
    # Do not manufacture instructions from the loader's zero-filled virtual tail.
    raw = section.raw[start:min(start + 15 * a.count, section.virtual_size)]
    md = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_32)
    instructions = list(md.disasm(raw, va, count=a.count))
    if not instructions:
        print(f"no complete file-backed instruction at preferred-image VA {va:#010x}", file=sys.stderr)
        return 2
    print(f"SHA-256 {env.TARGET_SHA256}; preferred-image VA, base {img.base:#010x}; {section.name}")
    if pointer_line:
        print(pointer_line)
    for ins in instructions:
        print(f"{ins.address:08x}  {ins.bytes.hex()}  {ins.mnemonic} {ins.op_str}".rstrip())
    return 0


