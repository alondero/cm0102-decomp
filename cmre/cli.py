def cmd_unblock(a) -> int:
    from . import ledger

    if a.batch:
        # Requeue everything the batch blocked (e.g. after a harness change); agent blocks stay.
        vas = [va for va, r in ledger.blocked().items() if r.get("by") == "batch"]
    elif a.va:
        vas = [_va(a.va)]
    else:
        raise SystemExit("give a function or --batch")
    for va in vas:
        ledger.blocked_path(va).unlink(missing_ok=True)
    print(f"unblocked {len(vas)}")
    return 0


def _batch_one(va: int) -> tuple[int, bool, str]:
    from . import recover

    try:
        ok, r = recover.accept_with_inference(va)
    except Exception as exc:  # noqa: BLE001 - a crash blocks the item, never the batch
        recover.block(va, f"harness-error: {type(exc).__name__}: {exc}"[:300], by="batch")
        return va, False, f"harness-error {exc}"[:120]
    if ok:
        d = r.get("difftest", {})
        return va, True, f"{r['status']} cov={d.get('coverage', '-')}"
    status = r.get("status")
    if status == "lift-blocked":
        reason = f"lift-blocked: {r['problems'][0]}"
    elif status == "fail":
        m = r["difftest"]["mismatches"][0]
        reason = f"mismatch: field={m.get('field')} case={m.get('case')}"
    elif status == "low-coverage":
        reason = f"low-coverage: {r['difftest']['coverage']} < {r['min_coverage']}"
    else:
        reason = f"{status}"
    recover.block(va, reason, r, by="batch")
    return va, False, reason


def cmd_batch(a) -> int:
    from . import inventory, queue, jobs

    inventory.load()  # build the cache once before workers start
    items = queue.frontier(a.n, a.max_bytes, a.min_bytes, a.module,
                           set(a.functions) if a.functions else None)
    job = jobs.Job('batch', [i.va for i in items],
                   {'n': a.n, 'max_bytes': a.max_bytes, 'min_bytes': a.min_bytes,
                    'module': a.module, 'functions': a.functions}, getattr(a, 'resume', None))
    print(f'Job receipt: {job.path}', flush=True)
    with ProcessPoolExecutor(max_workers=a.jobs) as pool:
        futures = [pool.submit(_batch_one, va) for va in job.pending]
        for fut in as_completed(futures):
            va, ok, msg = fut.result()
            job.record(va, ok, msg)
            print(f"fn_{va:08x} {'ACCEPT' if ok else 'BLOCK '} {msg}", flush=True)
    job.finish()
    print(f"batch: {len(job.data['results']) - job.failures}/{len(job.data['functions'])} accepted")
    return 0


def _revalidate_one(va: int, refresh: bool = False) -> tuple[int, str]:
    import json as _json

    from . import ledger, recover

    path = ledger.record_path(va)
    record = _json.loads(path.read_text(encoding="utf-8"))
    r = recover.test_lifted(va)
    if r["status"] != "pass":
        return va, f"FAIL {r['status']}"
    if r["source_sha256"] != record["lifted"]["source_sha256"]:
        return va, "DRIFT lifter output differs from the accepted source"
    if refresh and record.get("c"):
        # The lifted source was checked above. Preserve that baseline and
        # refresh the active C tier only after its own deterministic gate;
        # refresh=True also refuses changed accepted C source bytes. Do this
        # even when lifted evidence is current: C identity is independent.
        ok, result = recover.accept(va, 'c', refresh=True)
        if not ok:
            return va, f"FAIL refresh c {result.get('status')}"
        return va, 'ok'
    if refresh and record["lifted"].get("harness_sha256") != recover.harness_digest():
        # Publish only after validation; interruptions retain the old evidence.
        ok, result = recover.accept(va, refresh=True)
        if not ok:
            return va, f"FAIL refresh {result.get('status')}"
    return va, "ok"


def _revalidate_guarded(va: int, refresh: bool = False) -> tuple[int, str]:
    """One item's exception is that item's failure, never the whole job's.

    An exception (not a FAIL verdict) is retried once: a build tool can fail
    transiently, and the retry repeats the full test before recording a pass.
    """
    try:
        return _revalidate_one(va, refresh)
    except Exception as first:
        try:
            va, msg = _revalidate_one(va, refresh)
        except Exception as exc:
            return va, f"ERROR {type(exc).__name__}: {exc}"
        print(f"fn_{va:08x} retried after {type(first).__name__}: {first}", flush=True)
        return va, msg


def _legacy_revalidate(a) -> int:
    from . import ledger, jobs

    vas = [e.va for e in ledger.cmre_entries()][: a.n]
    job = jobs.Job('revalidate', vas, {'n': a.n, 'refresh': a.refresh}, getattr(a, 'resume', None),
                   retry_failed=getattr(a, 'retry_failed', False))
    print(f'Job receipt: {job.path}', flush=True)
    if a.jobs == 1:
        results = (_revalidate_guarded(va, a.refresh) for va in job.pending)
    else:
        pool = ProcessPoolExecutor(max_workers=a.jobs)
        results = (f.result() for f in as_completed([pool.submit(_revalidate_guarded, va, a.refresh) for va in job.pending]))
    try:
        for va, msg in results:
            job.record(va, msg == 'ok', msg)
            if msg != "ok":
                print(f"fn_{va:08x} {msg}", flush=True)
    finally:
        if a.jobs != 1:
            pool.shutdown(wait=True, cancel_futures=True)
    job.finish()
    count = len(job.data['functions'])
    print(f"revalidated {count}: {count - job.failures} ok, {job.failures} need attention")
    return 1 if job.failures else 0


def cmd_revalidate(a) -> int:
    from . import ledger, validation

    if a.retry_failed and not a.resume:
        raise ValueError('--retry-failed requires --resume')
    if a.n < 0 or a.jobs < 1:
        raise ValueError('Selection and worker count must be nonnegative/positive')
    if a.resume and a.reuse:
        raise ValueError('Select either --resume or --reuse')
    # Existing jobs retain their schema and strict resume contract.
    if getattr(a, 'resume', None):
        schema = validation.receipt_schema(Path(a.resume))
        if schema != validation.SCHEMA:
            if schema != 'cmre-job/2':
                raise ValueError('Unsupported resume schema; use current dependency-aware evidence or legacy schema-2 jobs')
            if a.plan or a.audit or a.compatibility or a.output:
                raise ValueError('Legacy --resume retains its original contract; use --reuse with a dependency-aware receipt')
            return _legacy_revalidate(a)
    vas = [e.va for e in ledger.cmre_entries()][:a.n]
    data = validation.plan(vas, refresh=a.refresh,
                           resume=a.resume, reuse=a.reuse, retry_failed=a.retry_failed,
                           audit=a.audit, compatibility=a.compatibility)
    if a.plan:
        if a.output:
            from . import coordination
            coordination.atomic_json(Path(a.output), data)
        print(json.dumps(data if a.json else validation.summary(data), indent=2))
        return 0
    if a.output:
        raise ValueError('--output requires --plan')
    if not a.audit and any('global execution/harness identity changed or unavailable' in item['reasons']
                           for item in data['items'].values() if item['action'] == 'execute'):
        raise ValueError('Unproven global harness change: inspect revalidate --plan first; '
                         'supply a verified --compatibility receipt or explicitly choose --audit. '
                         'No differential execution started.')
    print('Validation plan: ' + json.dumps(validation.summary(data)), flush=True)
    run = validation.Run(data)
    print(f'Job receipt: {run.path}', flush=True)
    pending = [(k, v) for k, v in data['items'].items() if v['action'] == 'execute']
    pool = None
    identity_hash = validation.digest(data['identity'])
    try:
        if a.jobs == 1:
            results = ((k, validation.execute(v, identity_hash, a.refresh)) for k, v in pending)
        else:
            pool = ProcessPoolExecutor(max_workers=a.jobs)
            futures = {pool.submit(validation.execute, v, identity_hash, a.refresh): k for k, v in pending}
            results = ((futures[f], f.result()) for f in as_completed(futures))
        for key, result in results:
            run.record(key, result)
            if not result['ok']:
                print(f"fn_{key} FAIL {result['detail']}", flush=True)
    finally:
        if pool:
            pool.shutdown(wait=True, cancel_futures=True)
        run.finish()
    print(json.dumps(run.data['summary'], indent=2))
    return 1 if run.data['summary']['failed'] or run.data.get('identity_drift') or run.data['state'] != 'finished' else 0


def cmd_verify(a) -> int:
    from . import ledger

    problems = ledger.verify()
    for p in problems:
        print(f"BAD {p}")
    print("ledgers verified" if not problems else f"{len(problems)} problem(s)")
    return 1 if problems else 0


def cmd_task(a) -> int:
    from . import tasks

    if a.action == 'metrics':
        print(json.dumps(tasks.metrics_summary(a.task_id), indent=2))
        return 0
    if a.action == 'prepare':
        result = tasks.prepare(_va(a.va))
    elif a.action == 'claim':
        result = tasks.claim(a.task_id, a.owner, lease_seconds=a.lease_seconds)
    elif a.action == 'submit':
        metrics = json.loads(a.metrics) if a.metrics else None
        result = tasks.submit(a.task_id, a.owner, a.token, outcome=a.outcome,
                              summary=a.summary, metrics=metrics)
    elif a.action == 'publish':
        result = tasks.publish(a.task_id)
    elif a.action == 'usage':
        result = tasks.record_usage(a.task_id, a.attempt, json.loads(a.metrics))
    elif a.action == 'revise':
        result = tasks.revise(a.task_id, a.reason)
    else:
        result = tasks.status(a.task_id)
    compact = ([tasks.summary(item) for item in result] if isinstance(result, list)
               else tasks.summary(result, include_token=a.action == 'claim'))
    print(json.dumps(compact, indent=2))
    if a.action == 'usage':
        return 0
    failed = isinstance(result, dict) and result.get('status') in (
        'failed-validation', 'exhausted', 'stale-input', 'publication-failed')
    if a.action == 'submit' and result.get('attempts'):
        failed |= result['attempts'][-1]['status'] != 'pass'
    return 1 if failed else 0


def cmd_job(a) -> int:
    from . import jobs

    print(json.dumps(jobs.describe(a.receipt), indent=2))
    return 0


