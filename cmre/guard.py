"""PreToolUse guard for Claude Code and Codex (`--codex`).

Reads {"tool_name", "tool_input"} on stdin. Exit 2 + stderr denies with a reason
the agent sees; a JSON "ask" defers to the user in Claude Code; silence allows.
Codex does not support "ask", so that mode blocks until the launcher supplies
the session's authorized paths. Standard library only, so it starts fast.
"""
from __future__ import annotations

import json
import os
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
# `cmre publication scan --commit REF` writes one receipt per scanned commit.
PUBLICATION_RECEIPTS = ROOT / "CM0102/Analysis/cmre/publication"

PROTECTED = [
    ("CM0102/Game/", "preserved official 3.9.68 install; work on copies (AGENTS.md)"),
    ("CM0102/Original-3.9.60/", "preserved original install"),
    ("CM0102/InstallMedia/", "supplied media must stay unmodified"),
    ("CM0102/Inspection/", "baseline manifests must not be regenerated or edited"),
    ("recovery/ledger/", "written only by `py -3.13 -m cmre accept`"),
    ("recovery/lifted/", "generated by `cmre accept`; write tier-2 C in recovery/c/ instead"),
    ("recovery/blocked/", "use `py -3.13 -m cmre block|unblock`"),
    ("recovery/date/", "legacy accepted records are frozen"),
    ("recovery/lang/", "legacy accepted records are frozen"),
    ("recovery/crt/", "legacy accepted records are frozen"),
    ("recovery/rng/", "legacy accepted records are frozen"),
    ("recovery/registry.json", "legacy registry is frozen"),
    ("docs/STATUS.md", "generated by `py -3.13 -m cmre status --write`"),
]
ASK = [("cmre/", "harness change: needs a failing test first and user approval"),
       ("tests/", "harness test change: needs user approval"),
       ("pytest.ini", "test configuration change")]
PROTECTED_WORDS = ("CM0102/Game", "CM0102\\Game", "Original-3.9.60", "InstallMedia", "CM0102/Inspection",
                   "CM0102\\Inspection", "recovery/ledger", "recovery\\ledger", "recovery/lifted", "recovery\\lifted")
MUTATING = re.compile(r"\b(rm|mv|del|rmdir|Remove-Item|Move-Item|Set-Content|Clear-Content|Add-Content|Out-File|sed\s+-i|truncate)\b")
# Output redirection is judged by its target: `2>&1`, `>/dev/null` and `2>$null` write nothing protected.
REDIRECT = re.compile(r"(?<![<>&-])\d?>>?(?!&)\s*([^\s;|&<>()]+)")
DISCARD = {"/dev/null", "$null", "nul"}
QUOTED = re.compile(r"""'[^']*'|"(?:\\.|[^"\\])*\"""")
BARE_PYTHON = re.compile(r"(^|[;&|(]\s*|\bthen\s+|\bdo\s+)python3?(\.exe)?\s")
GIT_PULL_OR_PUSH = re.compile(r"\bgit\s+(push|pull)\b")
# One ordinary fast-forward to main or a same-name PR branch, with an exact scan.
PUSH = re.compile(r"^\s*(?:rtk\s+)?git\s+push\s+origin\s+([A-Za-z0-9][\w./-]*):(?:refs/heads/)?([A-Za-z0-9][\w./-]*)\s*$")
PUSH_RULE = ("push only `git push origin <branch>:main` or `<branch>:<branch>` after "
             "`py -3.13 -m cmre publication scan --commit <branch>` passes for that exact commit")


def _rel(path: str) -> str:
    p = Path(path)
    if not p.is_absolute():
        p = ROOT / p
    # Lexical first: a linked local folder (CM0102 in a clone) resolves outside ROOT.
    for candidate, root in ((Path(os.path.abspath(p)), Path(os.path.abspath(ROOT))), (p.resolve(), ROOT.resolve())):
        try:
            return candidate.relative_to(root).as_posix()
        except ValueError:
            pass
    return p.as_posix()


def receipt_allows_push(path: Path, commit: str, remote: str) -> bool:
    """A receipt proves a passing scan of this commit's history for a private remote."""
    try:
        receipt = json.loads(Path(path).read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return False
    target = receipt.get("remote") if isinstance(receipt, dict) else None
    return isinstance(target, dict) and (
        receipt.get("schema"), receipt.get("commit"), receipt.get("result"),
        target.get("name"), target.get("visibility")) == (
        "cmre-publication-scan/1", commit, "pass", remote, "PRIVATE")


def _push(cmd: str) -> tuple[str, str]:
    """Allow a push only of a commit whose full reachable history passed the publication scan."""
    match = PUSH.match(cmd)
    if not match or match[2] not in ('main', match[1]):
        return "deny", PUSH_RULE
    source = match[1]
    if match[2] != 'main':
        if source.startswith('refs/'):
            return "deny", PUSH_RULE
        # Resolve an actual local branch: a tag with the same short name must
        # not turn the same-name PR form into a remote tag publication.
        source = 'refs/heads/' + source
    resolved = subprocess.run(["git", "rev-parse", "--verify", "--quiet", source + "^{commit}"],
                              cwd=ROOT, capture_output=True, text=True)
    commit = resolved.stdout.strip()
    if resolved.returncode or not re.fullmatch(r"[0-9a-f]{40}", commit):
        return "deny", f"{match[1]} is not a local commit; {PUSH_RULE}"
    if not receipt_allows_push(PUBLICATION_RECEIPTS / f"{commit}.json", commit, "origin"):
        return "deny", f"no passing private publication receipt for {commit}; {PUSH_RULE}"
    return "allow", ""


def decide(tool: str, tool_input: dict) -> tuple[str, str]:
    tool = tool.rsplit('.', 1)[-1]
    if tool == 'exec_command':
        tool, tool_input = 'PowerShell', {'command': tool_input.get('cmd', '')}
    if tool == 'apply_patch':
        patch = tool_input.get('command', tool_input.get('patch', tool_input.get('input', '')))
        destinations = re.findall(r'^\*\*\* (?:(?:Add|Update|Delete) File|Move to): (.+)$', patch, re.M)
        if not destinations:
            return 'deny', 'Patch has no recognized file destinations'
        decisions = [decide('Edit', {'file_path': path.strip()}) for path in destinations]
        return next((d for d in decisions if d[0] == 'deny'),
                    next((d for d in decisions if d[0] == 'ask'), ('allow', '')))
    if tool in ("Write", "Edit", "MultiEdit", "NotebookEdit"):
        rel = _rel(tool_input.get("file_path") or tool_input.get("notebook_path") or "")
        for prefix, why in PROTECTED:
            if rel == prefix.rstrip("/") or rel.startswith(prefix):
                return "deny", f"{rel}: {why}"
        # Set by a launcher only for paths explicitly authorized in the session.
        # This never overrides the preservation rules above.
        try:
            scopes = json.loads(os.environ.get('CMRE_AUTHORIZED_PATHS', '[]'))
        except ValueError:
            scopes = []
        if isinstance(scopes, list) and any(isinstance(p, str) and (
                rel == _rel(p).rstrip('/') or rel.startswith(_rel(p).rstrip('/') + '/')) for p in scopes):
            return 'allow', ''
        for prefix, why in ASK:
            if rel == prefix.rstrip("/") or rel.startswith(prefix):
                return "ask", f"{rel}: {why}"
        return "allow", ""
    if tool in ("Bash", "PowerShell"):
        cmd = tool_input.get("command", "")
        unquoted = QUOTED.sub("''", cmd)  # words inside quotes are data, not commands
        # Read-only Git is allowed. Reversible mutations still respect frozen
        # inputs and generated records, including within compound commands.
        if BARE_PYTHON.search(unquoted):
            return "deny", "`python` resolves to an unrelated venv here; use `py -3.13` (AGENTS.md)"
        if re.search(r"\btaskkill\b.*/+IM\b|\bStop-Process\b.*-Name\b|\b(pkill|killall)\b", cmd, re.I):
            return "deny", "never kill processes by image name (other programs die too); kill the specific PID tree"
        if re.search(r"\bgit\s+push\b", cmd):
            return _push(cmd)
        protected = [p.rstrip('/').lower() for p, _ in PROTECTED]
        names = lambda text: any(p in text.replace('\\', '/').lower() for p in protected)
        targets = [t for t in REDIRECT.findall(unquoted) if t.lower() not in DISCARD]
        if any(names(t) for t in targets):
            return "deny", "command would redirect output into a protected or generated path; use cmre commands"
        mutates = MUTATING.search(cmd) or re.search(r"\bgit\s+(rm|reset|checkout|restore|clean|rebase|cherry-pick)\b", cmd)
        if mutates and names(cmd):
            return "deny", "command would modify a protected or generated path; use cmre commands"
    return "allow", ""


def main() -> int:
    try:
        payload = json.loads(sys.stdin.read() or "{}")
    except json.JSONDecodeError:
        return 0
    verdict, reason = decide(payload.get("tool_name", ""), payload.get("tool_input") or {})
    if verdict == "ask" and "--codex" in sys.argv[1:]:
        verdict = "deny"
        reason += "; launcher must provide already-authorized paths in CMRE_AUTHORIZED_PATHS"
    if verdict == "deny":
        print(reason, file=sys.stderr)
        return 2
    if verdict == "ask":
        print(json.dumps({"hookSpecificOutput": {"hookEventName": "PreToolUse", "permissionDecision": "ask",
                                                 "permissionDecisionReason": reason}}))
    return 0


if __name__ == "__main__":
    sys.exit(main())
