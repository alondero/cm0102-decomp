"""ADR 0006 condition 4 audit of accepted C routines whose original calls __ftol.

Read-only toward the ledger: each accepted source is gated afresh under the current harness and
its per-site __ftol (and CIpow) mutants are generated by the same `operand_evidence.generate`
that farm and direct acceptance run. One JSON line per routine goes to OUT/results.jsonl; the
mutant evidence stays under the routine's run directory. --census skips the gates and reports
only whether each source writes its sites as individually mutable casts.
"""
from __future__ import annotations

import argparse
import concurrent.futures
import json
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from cmre import env, lift, operand_evidence, recover  # noqa: E402

HELPER = f'{operand_evidence.FTOL_HELPER:#010x}'


def candidates(names=None):
    """(fn, record) for accepted C tiers whose original callees include __ftol."""
    rows = []
    for path in sorted(env.LEDGER_DIR.glob('fn_*.json')):
        if names and path.stem not in names:
            continue
        record = json.loads(path.read_text(encoding='utf-8'))
        if record.get('c') and HELPER in (record.get('boundaries') or {}).get('original_callees', []):
            rows.append((path.stem, record))
    return rows


def audit(fn, record, census):
    va = int(fn[3:], 16)
    row = {'fn': fn, 'bytes': record['extent']['bytes']}
    source = env.ROOT / record['c']['source']
    try:
        raw = source.read_bytes()
    except OSError as exc:
        return {**row, 'outcome': 'source-missing', 'detail': str(exc)}
    if env.digest_bytes(raw) != record['c']['source_sha256']:
        return {**row, 'outcome': 'source-drift', 'detail': 'working source differs from the accepted bytes'}
    if census:
        lifted = lift.discover(va)
        gate = {'ftol_sites': recover.ftol_sites(lifted), 'builds': {}}
        row['sites'] = len(gate['ftol_sites'])
        try:
            bridge, ftol = operand_evidence.operand_mutant_sources(raw.decode('utf-8'), gate)
        except ValueError as exc:
            return {**row, 'outcome': 'blocked', 'detail': str(exc)[:400]}
        return {**row, 'outcome': 'mutable', 'mutants': len(bridge) + len(ftol)}
    started = time.monotonic()
    baseline = recover.test_c(va)
    row['sites'] = operand_evidence.ftol_site_count(baseline)
    if baseline.get('status') != 'pass':
        return {**row, 'outcome': 'gate-fail', 'detail': 'the accepted source no longer passes the current gate'}
    hints = env.HINTS_DIR / f'{fn}.json'
    hints_sha = env.digest(hints) if hints.exists() else None
    summary = env.RUNS / fn / f"c-{baseline['key']}" / 'ftol-audit' / str(time.time_ns()) / 'summary.json'
    blocker = operand_evidence.generate(
        summary, fn, None, raw, baseline, hints_sha,
        gate=lambda candidate: recover.test_c(va, source=candidate, profile=baseline['profile']),
        check_inputs=lambda: None if source.read_bytes() == raw else 'source changed during the audit',
        report_event=lambda status: None)
    return {**row, 'outcome': 'blocked' if blocker else 'killed', 'detail': (blocker or '')[:400],
            'evidence': env.rel(summary) if summary.exists() else None,
            'minutes': round((time.monotonic() - started) / 60, 1)}


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('fns', nargs='*', help='limit to these fn_XXXXXXXX (default: every candidate)')
    parser.add_argument('--out', type=Path, required=True, help='directory for results.jsonl')
    parser.add_argument('--census', action='store_true', help='structure only: no gate runs')
    parser.add_argument('--jobs', type=int, default=1, help='routines audited at once')
    a = parser.parse_args(argv)
    a.out.mkdir(parents=True, exist_ok=True)
    results = a.out / 'results.jsonl'
    done = set()
    if results.exists():   # resumable: a routine already written is not audited again
        done = {json.loads(line)['fn'] for line in results.read_text(encoding='utf-8').splitlines() if line}
    todo = [(fn, record) for fn, record in candidates(set(a.fns) or None) if fn not in done]
    print(f'{len(todo)} routine(s) to audit, {len(done)} already in {env.rel(results)}', flush=True)
    with concurrent.futures.ProcessPoolExecutor(max(1, a.jobs)) as pool, results.open('a', encoding='utf-8') as sink:
        futures = {pool.submit(audit, fn, record, a.census): fn for fn, record in todo}
        for future in concurrent.futures.as_completed(futures):
            try:
                row = future.result()
            except Exception as exc:   # one routine's harness error must not end the audit
                row = {'fn': futures[future], 'outcome': 'error', 'detail': f'{type(exc).__name__}: {exc}'[:400]}
            sink.write(json.dumps(row) + '\n')
            sink.flush()
            print(json.dumps(row), flush=True)
    rows = [json.loads(line) for line in results.read_text(encoding='utf-8').splitlines() if line]
    totals = {}
    for row in rows:
        count, size = totals.get(row['outcome'], (0, 0))
        totals[row['outcome']] = (count + 1, size + row.get('bytes', 0))
    print(json.dumps({outcome: {'fn': n, 'bytes': b} for outcome, (n, b) in sorted(totals.items())}))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
